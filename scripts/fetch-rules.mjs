// Downloads the official Magic Comprehensive Rules and splits them into one file per
// rule under docs/rules/, plus INDEX.md and glossary.txt. Run: npm run fetch-rules
// To pin a version, pass the .txt URL: npm run fetch-rules -- <url>
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { creatureTypesOf, subtypeListsOf } from './rules-lists.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'docs/rules');

const RULES_PAGE = 'https://magic.wizards.com/en/rules';
const HEADERS = { 'User-Agent': 'mtg-arena-edh-prototype/0.1' };

async function get(url) {
  const res = await fetch(url, { headers: HEADERS });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res;
}

// The file name carries its release date, so read the current link off the rules page.
async function findTxtUrl() {
  const html = await (await get(RULES_PAGE)).text();
  const m = html.match(/https:\/\/media\.wizards\.com\/[^"'<>\\]*?MagicCompRules[^"'<>\\]*?\.txt/i);
  if (!m) throw new Error(`No rules .txt link on ${RULES_PAGE}. Pass the URL as an argument.`);
  return m[0].replaceAll(' ', '%20');
}

// Older releases were Windows-1252, newer ones are UTF-8.
function decode(buf) {
  try {
    return new TextDecoder('utf-8', { fatal: true }).decode(buf);
  } catch {
    return new TextDecoder('windows-1252').decode(buf);
  }
}

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const url = process.argv[2] ?? (await findTxtUrl());
const text = decode(await (await get(url)).arrayBuffer());
const lines = text.split(/\r\n?|\n/).map((l) => l.trimEnd());

// Each heading appears twice: once in the table of contents, once where the text starts.
const bodyStart = lines.lastIndexOf('1. Game Concepts');
const glossaryStart = lines.lastIndexOf('Glossary');
const creditsStart = lines.lastIndexOf('Credits');
if (bodyStart < 0 || bodyStart > glossaryStart || glossaryStart > creditsStart) {
  throw new Error('Rules file layout not recognised. Has the format changed?');
}
const effective = text.match(/effective as of ([^.]+)\./)?.[1] ?? 'unknown date';

const chapters = [];
let rule = null;
for (const line of lines.slice(bodyStart, glossaryStart)) {
  if (/^\d\. /.test(line)) {
    chapters.push({ title: line, rules: [] });
    rule = null;
    continue;
  }
  const head = line.match(/^(\d{3})\. (.+)$/);
  if (head) {
    rule = { num: head[1], title: head[2], file: `${head[1]}-${slug(head[2])}.txt`, lines: [], subs: [] };
    chapters.at(-1).rules.push(rule);
  }
  if (!rule) continue;
  rule.lines.push(line);
  // Titled subrules such as "702.19. Trample". Ordinary subrules are full sentences.
  const sub = line.match(/^(\d{3}\.\d+)\. ([^.:]{1,60})$/);
  if (sub) rule.subs.push(`${sub[1]} ${sub[2]}`);
}

// Start clean so a rule that was renamed or removed doesn't leave a stale file behind.
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const index = [
  '# Magic Comprehensive Rules: index',
  '',
  `Effective ${effective}. Source: ${url}`,
  'Generated by `npm run fetch-rules`. Do not edit by hand.',
  '',
  'One file per rule. Glossary: `glossary.txt`.',
];
let count = 0;
for (const ch of chapters) {
  index.push('', `## ${ch.title}`, '');
  for (const r of ch.rules) {
    writeFileSync(join(outDir, r.file), r.lines.join('\n').trimEnd() + '\n');
    index.push(`- ${r.num} ${r.title}: \`${r.file}\``);
    for (const s of r.subs) index.push(`  - ${s}`);
    count++;
  }
}
writeFileSync(join(outDir, 'glossary.txt'), lines.slice(glossaryStart, creditsStart).join('\n').trimEnd() + '\n');
writeFileSync(join(outDir, 'INDEX.md'), index.join('\n') + '\n');

// Every creature type (205.3m), for choosing one (Cavern of Souls).
const typesLine = lines.find((l) => l.startsWith('205.3m'));
if (!typesLine) throw new Error('Rule 205.3m (creature types) not found');
const creatureTypes = creatureTypesOf(typesLine);
writeFileSync(join(root, 'src/cards/creature-types.json'), JSON.stringify(creatureTypes, null, 1) + '\n');
// The other card types' subtypes (205.3g-q), for which subtypes go with which card type (205.1a, 205.3d).
writeFileSync(join(root, 'src/cards/subtypes.json'), JSON.stringify(subtypeListsOf(lines), null, 1) + '\n');
console.log(`Wrote ${count} rules (effective ${effective}) to ${outDir}`);
